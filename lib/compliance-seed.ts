import type { TemplateSeed } from "./compliance";
export const seedMigration =
  "supabase/migrations/20261024120100_seed_compliance_templates.sql";
const text = (v: string | null) => (v === null ? "null" : `'${v.replaceAll("'", "''")}'`);
const json = (v: unknown) => `${text(JSON.stringify(v))}::jsonb`;
// SQL for the starter library. Existing codes are left untouched, so reviewed edits survive reruns.
export function templateSeedSql(templates: TemplateSeed[]) {
  const rows = templates.map((t) =>
    [
      text(t.code),
      text(t.area),
      text(t.title),
      text(t.form_name),
      text(t.description),
      text(t.objective),
      text(t.activity),
      text(t.frequency),
      json(t.deadline_rule),
      text(t.deadline_text),
      json(t.required_documents),
      json(t.official_references),
      json(t.applicability),
      text("Needs review"),
      text(t.review_notes),
      t.last_verified_on ? `${text(t.last_verified_on)}::date` : "null",
    ].join(","),
  );
  return [
    "-- Generated by scripts/build-template-seed.mjs from data/compliance-templates.ts. Do not edit by hand.",
    "-- Starter compliance library. Every template starts as Needs review.",
    "begin;",
    "insert into public.compliance_templates(code,area,title,form_name,description,objective,activity,frequency,deadline_rule,deadline_text,required_documents,official_references,applicability,review_status,review_notes,last_verified_on) values",
    rows.map((r) => `(${r})`).join(",\n"),
    "on conflict (code) do nothing;",
    "commit;",
    "",
  ].join("\n");
}
